#!/usr/bin/env python3
"""writes src/tables/dsp_tables.c, closed-form values computed in double and rounded to float"""
import math
import os
import re
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'tables', 'dsp_tables.c')
TABLES = os.path.join(ROOT, 'src', 'tables', 'tables.c')

DCT_BLK_J_MAX = 17   # XOMBE_DCT_BLK_J_MAX, largest spectral block length (xombe__blk)
DCT_BLK_ROWS = 6     # XOMBE_DCT_BLK_ROWS, one kernel row per DCT coefficient m = 0..5
GRAIN_RAMP = 16  # XOMBE_GRAIN_RAMP
HALF_MIN, HALF_MAX = 76, 84
LMAX = 56
B0_COUNT = 120
TW_N = 1024          # analysis FFT, smaller transforms take every (TW_N/n)-th twiddle
FFT = 1024           # XOMBE_FFT
BASE_WINDOW = 199
PITCH_LPF_HALF = 10
PITCH_WIN = 301
TONE_SEG = 240
TONE_FFT = 512       # XOMBE_TONE_FFT


def f32(x):
    """x rounded to the nearest float, printed to read back exactly"""
    if abs(x) < 1e-12:  # cos(pi/2) and similar are exactly 0
        x = 0.0
    v = struct.unpack('f', struct.pack('f', x))[0]
    s = '%.9g' % v
    if 'e' not in s and '.' not in s:
        s += '.0'
    return s + 'f'


def fl32(x):
    """x rounded to float, the result of a float operation whose exact value is x"""
    return struct.unpack('f', struct.pack('f', x))[0]


def round_q(v):
    """(int)(v + (v < 0 ? -0.5f : 0.5f)) for float v"""
    return int(fl32(v + (-0.5 if v < 0 else 0.5)))


def rows(values, per_line=6, indent='    '):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + ', '.join(values[i:i + per_line]) + ',')
    return '\n'.join(lines)


def w0_table():
    """xombe__w0 as spelled in tables.c (the standard's pitch table as float)"""
    src = open(TABLES).read()
    body = re.search(r'xombe__w0\[XOMBE_B0_COUNT\] = \{(.*?)\};', src, re.S).group(1)
    vals = [struct.unpack('f', struct.pack('f', float(v.rstrip('f'))))[0] for v in body.replace(',', ' ').split()]
    assert len(vals) == B0_COUNT and all(a > b for a, b in zip(vals, vals[1:]))
    return vals


def hamming(i, n):
    return 0.54 - 0.46 * math.cos(2.0 * math.pi * i / (n - 1))


def dct(J, m, i):
    return math.cos(math.pi * m * (i + 0.5) / J)


def main():
    out = ['/* generated by scripts/gen_dsp_tables.py, do not edit */', '#include "dsp_tables.h"', '']

    out.append('const float xombe__dct8[8][8] = {')
    for m in range(8):
        out.append('    {' + ', '.join(f32(dct(8, m, i)) for i in range(8)) + '},')
    out.append('};')
    out.append('')

    offs, vals = [], []
    for J in range(DCT_BLK_J_MAX + 1):
        offs.append(str(len(vals)))
        for m in range(DCT_BLK_ROWS):
            vals.extend(f32(dct(J, m, i)) for i in range(J))
    out.append('const unsigned short xombe__dct_blk_off[XOMBE_DCT_BLK_J_MAX + 1] = {')
    out.append(rows(offs, 12))
    out.append('};')
    out.append('')
    out.append('const float xombe__dct_blk[XOMBE_DCT_BLK_SIZE] = {')
    out.append(rows(vals))
    out.append('};')
    out.append('')

    out.append('const float xombe__ramp_cos[XOMBE_GRAIN_RAMP] = {')
    out.append(rows([f32(math.cos(math.pi * j / GRAIN_RAMP)) for j in range(GRAIN_RAMP)]))
    out.append('};')
    out.append('')
    out.append('const float xombe__ramp_sin[XOMBE_GRAIN_RAMP] = {')
    out.append(rows([f32(math.sin(math.pi * j / GRAIN_RAMP)) for j in range(GRAIN_RAMP)]))
    out.append('};')
    out.append('')

    out.append('const float xombe__sqrt_n[XOMBE_HALF_MAX + 1] = {')
    out.append(rows([f32(math.sqrt(n)) for n in range(HALF_MAX + 1)]))
    out.append('};')
    out.append('')
    out.append('const float xombe__rsqrt_half[XOMBE_HALF_MAX - XOMBE_HALF_MIN + 1] = {')
    out.append(rows([f32(1.0 / math.sqrt(N)) for N in range(HALF_MIN, HALF_MAX + 1)]))
    out.append('};')
    out.append('')

    out.append('const float xombe__half_log2[XOMBE_LMAX + 1] = {')
    out.append(rows(['0.0f'] + [f32(0.5 * math.log2(L)) for L in range(1, LMAX + 1)]))
    out.append('};')
    out.append('')

    w0 = w0_table()
    out.append('const float xombe__w0_mid[XOMBE_B0_COUNT - 1] = {')
    out.append(rows([f32(math.sqrt(w0[b] * w0[b + 1])) for b in range(B0_COUNT - 1)]))
    out.append('};')
    out.append('')

    out.append('const xombe_cpx xombe__fft_tw[XOMBE_TW_N / 2] = {')
    tw = []
    for k in range(TW_N // 2):
        ang = -2.0 * math.pi * k / TW_N
        tw.append('{%s, %s}' % (f32(math.cos(ang)), f32(math.sin(ang))))
    out.append(rows(tw, 3))
    out.append('};')
    out.append('')

    out.append('#if XOMBE_HAVE_ENCODER')
    out.append('const float xombe__base_win[XOMBE_BASE_WINDOW] = {')
    out.append(rows([f32(hamming(i, BASE_WINDOW)) for i in range(BASE_WINDOW)]))
    out.append('};')
    out.append('')

    h = []
    for j in range(-PITCH_LPF_HALF, PITCH_LPF_HALF + 1):
        x = 0.25 * j
        sinc = 1.0 if j == 0 else math.sin(math.pi * x) / (math.pi * x)
        h.append(0.25 * sinc * (0.54 + 0.46 * math.cos(math.pi * j / PITCH_LPF_HALF)))
    s = 0.0
    for v in h:
        s += v
    lpf = [f32(float(f32(v)[:-1]) / s) for v in h]
    out.append('const float xombe__pitch_lpf[2 * XOMBE_PITCH_LPF_HALF + 1] = {')
    out.append(rows(lpf))
    out.append('};')
    out.append('')

    # q15 low-pass taps (kern_q15_pitch.c) from the float taps, in float arithmetic as C computes it
    # g[m] = h[20 - m] scaled so sum |g| <= 65536 after rounding (a 32-bit SMLAD sum of int16 can't overflow),
    # paired, and again shifted by one
    lpf = [fl32(float(v[:-1])) for v in lpf]
    total = 0.0
    for v in lpf:
        total = fl32(total + abs(v))
    gain = fl32(65000.0 / total)
    g = [round_q(fl32(lpf[2 * PITCH_LPF_HALF - m] * gain)) for m in range(2 * PITCH_LPF_HALF + 1)]
    taps = 2 * PITCH_LPF_HALF + 2
    ga = g + [0] * (taps - len(g))
    gb = [0] + g + [0] * (taps - 1 - len(g))
    def pairs(t):
        return ['0x%08xu' % ((t[i] & 0xffff) | (t[i + 1] & 0xffff) << 16) for i in range(0, taps, 2)]
    out.append('#if XOMBE_KERNELS_Q15')
    out.append('const uint32_t xombe__pitch_lpf_q15[2][XOMBE_PITCH_LPF_PAIRS] = {')
    for t in (ga, gb):
        out.append('    {')
        out.append(rows(pairs(t), 6, ' ' * 8))
        out.append('    },')
    out.append('};')
    out.append('const float xombe__pitch_lpf_q15_gain = %s;' % f32(gain))
    def q15(v):
        return min(32767, math.floor(v * 32768.0 + 0.5)) & 0xffff
    tq = []
    for j in range(FFT // 4):
        ang = -2.0 * math.pi * j / (FFT // 2)
        tq.append('0x%08xu' % (q15(math.cos(ang)) | q15(math.sin(ang)) << 16))
    out.append('const uint32_t xombe__fft_tw_q15[XOMBE_FFT / 4] = {')
    out.append(rows(tq, 6))
    out.append('};')
    tq = []
    for j in range(TONE_FFT // 4):
        ang = -2.0 * math.pi * j / (TONE_FFT // 2)
        tq.append('0x%08xu' % (q15(math.cos(ang)) | q15(math.sin(ang)) << 16))
    out.append('const uint32_t xombe__tone_tw_q15[XOMBE_TONE_FFT / 4] = {')
    out.append(rows(tq, 6))
    out.append('};')
    out.append('#endif')
    out.append('')

    w = [hamming(j, PITCH_WIN) for j in range(PITCH_WIN)]
    s2 = s4 = 0.0
    for v in w:
        s2 += v * v
    w2 = [v * v / s2 for v in w]
    for v in w2:
        s4 += v * v
    out.append('const float xombe__pitch_w2[XOMBE_PITCH_WIN] = {')
    out.append(rows([f32(v) for v in w2]))
    out.append('};')
    out.append('const float xombe__pitch_sum_w4 = %s;' % f32(s4))
    # q15 pitch window (kern_q15_pitch.c) from the float table, scaled to peak 32767, first half (symmetric)
    w2f = [fl32(float(f32(v)[:-1])) for v in w2]
    w2_gain = fl32(32767.0 / max(w2f))
    w2q = [round_q(fl32(v * w2_gain)) for v in w2f]
    assert w2q == w2q[::-1]
    w2q = w2q[:PITCH_WIN // 2 + 1]
    out.append('#if XOMBE_KERNELS_Q15')
    out.append('const int16_t xombe__pitch_w2_q15[XOMBE_PITCH_HALF + 1] = {')
    out.append(rows([str(v) for v in w2q], 12))
    out.append('};')
    out.append('const float xombe__pitch_w2_q15_gain = %s;' % f32(w2_gain))
    out.append('#endif')
    out.append('')

    out.append('const float xombe__tone_win[XOMBE_TONE_SEG] = {')
    out.append(rows([f32(0.5 - 0.5 * math.cos(2.0 * math.pi * i / (TONE_SEG - 1))) for i in range(TONE_SEG)]))
    out.append('};')
    out.append('#endif')

    assert len(vals) == DCT_BLK_ROWS * sum(range(DCT_BLK_J_MAX + 1))
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
